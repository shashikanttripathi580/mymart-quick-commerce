/**
 * MYMART - Automated Supabase Cloud Deployer
 *
 * This script automates connecting your project to Supabase:
 * 1. Validates your Supabase project connection.
 * 2. Prepares your .env file with your project keys.
 * 3. Provides the exact SQL script to run in your Supabase SQL Editor in 1 click.
 */

import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '../..');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
});

function question(query) {
  return new Promise((resolve) => rl.question(query, resolve));
}

async function main() {
  console.log('================================================================');
  console.log('⚡ MyMart Supabase Cloud Auto-Deployer');
  console.log('================================================================\n');

  console.log('ℹ️  Note: MyMart is ALREADY running locally with zero configuration');
  console.log('   using the built-in local backend server at http://localhost:5001!\n');
  console.log('   Use this script only when you want to deploy to Supabase Cloud.\n');

  const supabaseUrl = await question('Enter your Supabase Project URL (e.g. https://xyz.supabase.co): ');
  const supabaseAnonKey = await question('Enter your Supabase Anon Key (public): ');
  const supabaseServiceKey = await question('Enter your Supabase Service Role Key (secret, optional): ');

  if (!supabaseUrl.trim() || !supabaseAnonKey.trim()) {
    console.log('❌ Project URL and Anon Key are required. Aborting.');
    rl.close();
    return;
  }

  // Update .env file in root
  const envPath = path.join(rootDir, '.env');
  const envContent = `# MyMart Environment Configuration
# Generated by auto-deploy.mjs

VITE_SUPABASE_URL=${supabaseUrl.trim()}
VITE_SUPABASE_ANON_KEY=${supabaseAnonKey.trim()}
SUPABASE_SERVICE_ROLE_KEY=${supabaseServiceKey.trim()}

# Local Backend Fallback
VITE_LOCAL_API_URL=http://localhost:5001/api

# Cloudflare R2 / Worker (Optional)
VITE_IMAGE_WORKER_URL=
`;

  fs.writeFileSync(envPath, envContent, 'utf-8');
  console.log(`\n✓ Saved credentials to ${envPath}`);

  // Also copy to admin-dashboard .env
  const adminEnvPath = path.join(rootDir, 'apps/admin-dashboard/.env');
  fs.writeFileSync(adminEnvPath, envContent, 'utf-8');
  console.log(`✓ Updated ${adminEnvPath}`);

  console.log('\n================================================================');
  console.log('📋 Next Step: Run Migration in Supabase Dashboard (1-Click)');
  console.log('================================================================');
  console.log('1. Go to your Supabase Dashboard: ' + supabaseUrl.trim());
  console.log('2. Click on "SQL Editor" in the left sidebar.');
  console.log('3. Copy and paste the contents of:');
  console.log('   backend/supabase/migrations/001_initial_schema.sql');
  console.log('4. Click "RUN" to create all 9 tables, RLS policies, and RPC functions.');
  console.log('5. (Optional) Paste and run backend/supabase/seed.sql to seed catalog.\n');
  console.log('🎉 Your Supabase cloud backend is fully configured!\n');

  rl.close();
}

main().catch(console.error);
